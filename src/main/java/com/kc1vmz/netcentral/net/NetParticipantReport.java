import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.time.Instant;
import java.time.ZoneId;
import java.time.format.DateTimeFormatter;
import java.util.*;
import org.apache.pdfbox.pdmodel.*;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.PDType0Font;

/** Archived participation log using the original Net Central 309 form layout. */
public final class NetParticipantReport {
    private static final float WIDTH = 548, LEFT = 32, SIZE = 9, LEADING = 11;
    private static final float[] COLUMNS = {170, 114, 114, 150};
    private final ZoneId zone = ZoneId.systemDefault();
    private final DateTimeFormatter date = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm z").withZone(zone);

    private String time(Instant value) {
        return value == null ? "" : date.format(value);
    }

    public byte[] render(NetModels.Snapshot snapshot) throws IOException {
        var net = snapshot.net();
        List<String[]> entries = new ArrayList<>();
        Set<String> attended = new HashSet<>();
        for (var p : snapshot.participants()) {
            attended.add(root(p.callsign()));
            String callsign = p.callsign() + (text(p.tacticalCallsign()).isBlank() ? "" : " (" + p.tacticalCallsign() + ")");
            entries.add(new String[]{callsign, time(p.startTime()), time(p.endTime()),
                    text(p.electricalPowerType()) + ":" + text(p.radioStyle()) + ":" + text(p.transmitPower()) + "W"});
        }
        for (String expected : new TreeSet<>(snapshot.expectedParticipants()))
            if (!attended.contains(root(expected)))
                entries.add(new String[]{expected, "Did not participate", "", ""});
        entries.sort(Comparator.comparing(row -> row[0], String.CASE_INSENSITIVE_ORDER));
        try (PDDocument document = new PDDocument();
                var input = PDDocument.class.getResourceAsStream("/org/apache/pdfbox/resources/ttf/LiberationSans-Regular.ttf")) {
            PDType0Font font = PDType0Font.load(document, input);
            List<Row> header = List.of(
                    row(font, new float[]{200, 100, 248}, "COMMUNICATIONS LOG", "TASK #", "DATE / TIME PREPARED: " + time(Instant.now())),
                    row(font, new float[]{274, 274}, "OPERATIONAL PERIOD\nFrom: " + time(net.startTime()) + "\nTo: " + time(net.endTime()), "TASK NAME: " + text(net.name())),
                    row(font, new float[]{274, 274}, "RADIO OPERATOR NAME: " + text(net.creatorName()), "STATION I.D.: " + net.callsign()),
                    row(font, new float[]{WIDTH}, "LOG"),
                    row(font, COLUMNS, "CALLSIGN", "START", "END", "DETAILS"));
            float available = 760 - 90;
            for (Row r : header) available -= r.height();
            List<List<Row>> pages = new ArrayList<>();
            List<Row> current = new ArrayList<>();
            float used = 0;
            for (String[] entry : entries) {
                Row r = row(font, COLUMNS, entry);
                if (r.height() > available) throw new IOException("Participation entry exceeds printable page height");
                if (current.size() == 25 || used + r.height() > available) {
                    pages.add(current); current = new ArrayList<>(); used = 0;
                }
                current.add(r); used += r.height();
            }
            if (!current.isEmpty() || pages.isEmpty()) pages.add(current);
            for (int index = 0; index < pages.size(); index++) {
                PDPage page = new PDPage(PDRectangle.LETTER); document.addPage(page);
                try (PDPageContentStream stream = new PDPageContentStream(document, page)) {
                    float y = 760;
                    for (int h = 0; h < header.size(); h++) y = draw(stream, font, header.get(h), y, h == 3);
                    for (Row r : pages.get(index)) y = draw(stream, font, r, y, false);
                    Row blank = row(font, COLUMNS, "", "", "", "");
                    for (int count = pages.get(index).size(); count < 25 && y - blank.height() >= 90; count++)
                        y = draw(stream, font, blank, y, false);
                    draw(stream, font, row(font, new float[]{274, 274}, "Page " + (index + 1) + " of " + pages.size(), "ICS 309 Form"), 76, false);
                    draw(stream, font, row(font, new float[]{WIDTH}, "309 communications log generated by Net Central | Times: " + zone), 53, false);
                }
            }
            document.getDocumentInformation().setTitle("ICS 309 - " + net.callsign() + " - " + net.name());
            ByteArrayOutputStream bytes = new ByteArrayOutputStream(); document.save(bytes); return bytes.toByteArray();
        }
    }

    private static String root(String call) { return call.toUpperCase(Locale.ROOT).split("-")[0]; }
    private static String text(String value) { return value == null ? "" : value; }
    private record Row(float[] widths, List<List<String>> cells, float height) {}

    private Row row(PDType0Font font, float[] widths, String... values) throws IOException {
        List<List<String>> cells = new ArrayList<>(); int lines = 1;
        for (int i = 0; i < values.length; i++) {
            List<String> wrapped = wrap(font, text(values[i]), widths[i] - 10);
            cells.add(wrapped); lines = Math.max(lines, wrapped.size());
        }
        return new Row(widths, cells, Math.max(20, lines * LEADING + 8));
    }

    private List<String> wrap(PDType0Font font, String text, float width) throws IOException {
        List<String> lines = new ArrayList<>(); StringBuilder line = new StringBuilder();
        for (int code : text.codePoints().toArray()) {
            if (code == '\n' || code == '\r') { lines.add(line.toString()); line.setLength(0); continue; }
            String character = new String(Character.toChars(code));
            try { font.encode(character); } catch (IllegalArgumentException unsupported) { character = "?"; }
            if (font.getStringWidth(line + character) / 1000 * SIZE > width) {
                lines.add(line.toString()); line.setLength(0);
            }
            line.append(character);
        }
        lines.add(line.toString()); return lines;
    }

    private float draw(PDPageContentStream stream, PDType0Font font, Row row, float top, boolean dark) throws IOException {
        float x = LEFT;
        for (int i = 0; i < row.widths().length; i++) {
            if (dark) { stream.setNonStrokingColor(.18f); stream.addRect(x, top-row.height(), row.widths()[i], row.height()); stream.fill(); }
            stream.setStrokingColor(0f); stream.setLineWidth(.6f);
            stream.addRect(x, top-row.height(), row.widths()[i], row.height()); stream.stroke();
            stream.setNonStrokingColor(dark ? 1f : 0f); stream.beginText(); stream.setFont(font, SIZE);
            stream.setLeading(LEADING); stream.newLineAtOffset(x+5, top-12);
            for (String line : row.cells().get(i)) { stream.showText(line); stream.newLine(); }
            stream.endText(); x += row.widths()[i];
        }
        return top-row.height();
    }
}
